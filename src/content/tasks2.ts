const S = 'zu_pruefen' as const;

/** Kurzschreibweise für Einfachauswahl: erste Option ist richtig; die Anzeige wird gemischt. */
function sc(id: string, lesson: string | string[], objective: string, level: TaskLevel, category: ErrorCategory, src: string, prompt: string, correct: string, wrong: [string, string, ErrorCategory?][], explanation: string): Task {
  const opts: ChoiceOption[] = [{ id: 'a', text: correct }, ...wrong.map(([text, why, cat], i) => ({ id: String.fromCharCode(98 + i), text, why, category: cat ?? category }))];
  // deterministische Reihenfolge, damit die richtige Antwort nicht immer oben steht
  const rot = id.length % opts.length;
  const options = [...opts.slice(rot), ...opts.slice(0, rot)];
  return { id, type: 'single', prompt, level, lessons: Array.isArray(lesson) ? lesson : [lesson], objective, category, sources: [{ id: src }], status: S, options, correct: 'a', explanation };
}

